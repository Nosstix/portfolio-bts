<div class="bts-container">
    <h1 class="bts-title">Le BTS SIO – Services Informatiques aux Organisations</h1>
    <p class="bts-subtitle">
        Une formation en deux ans orientée vers les métiers de l’informatique : développement d’applications,
        administration de systèmes et de réseaux, support aux utilisateurs.
    </p>

    <div class="bts-section">
        <h2>🎓 Présentation générale</h2>
        <p>
            Le <strong>BTS SIO</strong> (Services Informatiques aux Organisations) est un diplôme de niveau
            Bac+2 qui prépare à intervenir dans le système d’information d’une entreprise ou d’une organisation :
        </p>
        <ul>
            <li>Analyser les besoins des utilisateurs et des clients,</li>
            <li>Participer à la conception d’applications et de services,</li>
            <li>Assurer la mise en production, la maintenance et le support,</li>
            <li>Contribuer à la sécurité du système d’information.</li>
        </ul>
        <p>
            La formation alterne entre <strong>cours théoriques</strong>, <strong>travaux pratiques</strong>,
            <strong>projets</strong> et, dans mon cas, <strong>alternance en entreprise</strong>.
        </p>
    </div>

    <div class="bts-section">
        <h2>🧭 Les deux options : SISR et SLAM</h2>
        <p>
            En deuxième année, le BTS SIO se divise en deux options :
        </p>

        <div class="bts-options-grid">
            <div class="bts-option">
                <h3>Option SISR – Solutions d’Infrastructure, Systèmes et Réseaux</h3>
                <p>
                    Cette option est orientée <strong>infrastructure</strong>. Les étudiants apprennent à :
                </p>
                <ul>
                    <li>Installer, configurer et maintenir des serveurs,</li>
                    <li>Gérer des réseaux (LAN, WAN, VLAN, etc.),</li>
                    <li>Superviser la sécurité et la disponibilité des services,</li>
                    <li>Mettre en place des solutions de virtualisation et de sauvegarde.</li>
                </ul>
                <p>
                    Elle est idéale pour ceux qui souhaitent devenir <strong>administrateur système/réseau</strong>,
                    <strong>technicien support</strong> ou <strong>technicien d’exploitation</strong>.
                </p>
            </div>

            <div class="bts-option">
                <h3>Option SLAM – Solutions Logicielles et Applications Métiers</h3>
                <p>
                    Cette option se concentre sur le <strong>développement</strong> :
                </p>
                <ul>
                    <li>Conception et programmation d’applications (web, desktop, mobile),</li>
                    <li>Modélisation de bases de données (MCD, MLD, SQL),</li>
                    <li>Développement avec des architectures structurées (MVC, APIs, etc.),</li>
                    <li>Intégration de la sécurité dans les applications.</li>
                </ul>
                <p>
                    Elle prépare aux métiers de <strong>développeur d’applications</strong>,
                    <strong>développeur web</strong> ou <strong>analyste-programmeur</strong>.
                </p>
            </div>
        </div>
    </div>

    <div class="bts-section">
        <h2>💻 Pourquoi j’ai choisi l’option SLAM</h2>
        <p>
            J’ai choisi l’option <strong>SLAM</strong> car je suis particulièrement attiré par le
            <strong>développement logiciel</strong> et la création d’applications utiles au quotidien :
        </p>
        <ul>
            <li>J’aime concevoir une interface, réfléchir au fonctionnement d’une application,</li>
            <li>J’apprécie la logique des langages de programmation et la résolution de problèmes,</li>
            <li>Je trouve motivant de voir un projet évoluer du cahier des charges au produit fonctionnel.</li>
        </ul>
        <p>
            L’option SLAM me permet aussi de travailler sur :
        </p>
        <ul>
            <li>Des projets concrets (sites web, outils internes, mini-applications métiers),</li>
            <li>Des bases de données et des APIs,</li>
            <li>Des notions de sécurité (droits utilisateurs, protections des données, etc.).</li>
        </ul>
    </div>

    <div class="bts-section">
        <h2>📚 Technologies vues (ou en cours d’apprentissage)</h2>
        <p>
            Au fil du BTS SIO et de l’alternance, je découvre progressivement différentes technologies :
        </p>
        <ul>
            <li><span class="bts-highlight">Langages :</span> PHP, SQL, C, Java, Python…</li>
            <li><span class="bts-highlight">Web :</span> HTML, CSS, Bootstrap…</li>
            <li><span class="bts-highlight">Backend & données :</span> PHP procédural puis MVC, MySQL.</li>
            <li><span class="bts-highlight">Environnement :</span> Linux (debian), hébergement web, Git / GitHub.</li>
        </ul>
        <p>
            L’objectif n’est pas seulement d’apprendre des langages, mais surtout de comprendre
            <strong>comment concevoir une application complète</strong> : analyser un besoin,
            modéliser les données, développer, tester, déployer et maintenir.
        </p>
    </div>

    <div class="bts-section">
