    <h1 class="bts-title">Le BTS SIO – Services Informatiques aux Organisations</h1>
    <p class="bts-subtitle">
        Une formation en deux ans orientée informatique, avec une spécialisation en développement ou en infrastructure selon l’option choisie.
    </p>

    <div class="bts-section">
        <h2><i class="fas fa-graduation-cap"></i> L’essentiel</h2>
        <p>
            Le <strong>BTS SIO</strong> est un diplôme Bac+2 qui prépare à travailler dans le système d’information d’une entreprise.
            On y apprend à analyser un besoin, développer ou maintenir une solution, gérer des données et prendre en compte la sécurité.
        </p>
        <p>
            La formation mélange cours, pratique, projets et, dans mon cas, alternance. C’est justement ce mélange qui permet de voir autre chose que de la théorie pure.
        </p>
    </div>

    <div class="bts-section">
        <h2><i class="fas fa-compass"></i> Les deux options</h2>
        <div class="bts-options-grid">
            <div class="bts-option">
                <h3>SISR</h3>
                <p>Option orientée systèmes, réseaux et administration d’infrastructure.</p>
                <ul>
                    <li>Installation et configuration de serveurs</li>
                    <li>Gestion réseau et supervision</li>
                    <li>Sécurité, sauvegarde, disponibilité</li>
                </ul>
            </div>

            <div class="bts-option">
                <h3>SLAM</h3>
                <p>Option centrée sur le développement d’applications et les bases de données.</p>
                <ul>
                    <li>Développement web ou logiciel</li>
                    <li>Conception de base de données</li>
                    <li>Architecture, logique métier, sécurité</li>
                </ul>
            </div>
        </div>
    </div>

    <div class="bts-section">
        <h2><i class="fas fa-laptop-code"></i> Pourquoi j’ai choisi SLAM</h2>
        <p>
            J’ai choisi <strong>SLAM</strong> parce que je préfère construire quelque chose de concret : réfléchir au besoin, organiser les données, coder, tester et améliorer.
            C’est l’option qui correspond le plus à ce que j’aime faire au quotidien.
        </p>
        <ul>
            <li>Développement web et applications métiers</li>
            <li>Bases de données, API, MVC, organisation de projet</li>
            <li>Prise en compte de la sécurité dans les applications</li>
        </ul>
    </div>

