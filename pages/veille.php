document.addEventListener('DOMContentLoaded', function() {
    const rssList = document.getElementById('rss-list');
    const rssStatus = document.getElementById('rss-status');

    const keywords = [
        'dram', 'ddr5', 'ddr4', 'ram', 'memory', 'mémoire',
        'nand', 'ssd', 'flash', 'hbm', 'hbm3e', 'hbm4',
        'vram', 'gddr', 'micron', 'sk hynix', 'samsung', 'kioxia', 'ai server', 'datacenter'
    ];

    const feeds = [{
            name: 'TrendForce',
            url: 'https://www.trendforce.com/feed/Semiconductors.html'
        },
        {
            name: 'Tom’s Hardware',
            url: 'https://www.tomshardware.com/feeds/rss2/all.xml'
        },
        {
            name: 'TechPowerUp',
            url: 'https://www.techpowerup.com/rss/news'
        }
    ];

    const fallbackArticles = [{
            title: 'TrendForce – hausse DRAM/NAND au 2e trimestre 2026',
            link: 'https://www.trendforce.com/presscenter/news/20260331-12995.html',
            source: 'Source de secours'
        },
        {
            title: 'Reuters – SK hynix, forte demande IA et HBM',
            link: 'https://www.reuters.com/world/asia-pacific/nvidia-supplier-sk-hynix-q1-profit-rises-406-meets-forecasts-2026-04-22/',
            source: 'Source de secours'
        },
        {
            title: 'Reuters – Kioxia portée par la demande mémoire liée à l’IA',
            link: 'https://www.reuters.com/world/asia-pacific/memory-maker-kioxia-sees-82-billion-q1-profit-ai-boom-2026-05-15/',
            source: 'Source de secours'
        }
    ];

    function addItem(article) {
        const li = document.createElement('li');
        li.className = 'rss-item';

        const a = document.createElement('a');
        a.href = article.link || '#';
        a.target = '_blank';
        a.rel = 'noopener';
        a.textContent = article.title || 'Article';

        const meta = document.createElement('div');
        meta.className = 'rss-date';
        meta.textContent = article.source || article.date || '';

        li.appendChild(a);
        li.appendChild(meta);
        rssList.appendChild(li);
    }

    function showFallback(message) {
        rssStatus.textContent = message || 'Le flux en direct ne répond pas. Affichage des liens de secours :';
        fallbackArticles.forEach(addItem);
    }

    function normalizeDate(dateValue) {
        if (!dateValue) return '';
        const date = new Date(dateValue);
        if (isNaN(date.getTime())) return '';
        return date.toLocaleDateString('fr-FR');
    }

    function articleMatches(article) {
        const haystack = ((article.title || '') + ' ' + (article.description || '')).toLowerCase();
        return keywords.some(keyword => haystack.includes(keyword));
    }

    async function loadFeed(feed) {
        const apiUrl = 'https://api.rss2json.com/v1/api.json?rss_url=' + encodeURIComponent(feed.url);
        const response = await fetch(apiUrl);
        if (!response.ok) throw new Error('Flux indisponible : ' + feed.name);

        const data = await response.json();
        if (!data.items || !Array.isArray(data.items)) return [];

        return data.items
            .filter(articleMatches)
            .slice(0, 4)
            .map(item => ({
                title: item.title,
                link: item.link,
                date: normalizeDate(item.pubDate),
                source: feed.name + (normalizeDate(item.pubDate) ? ' • ' + normalizeDate(item
                    .pubDate) : '')
            }));
    }

    Promise.allSettled(feeds.map(loadFeed))
        .then(results => {
            const articles = results
                .filter(result => result.status === 'fulfilled')
                .flatMap(result => result.value);

            const uniqueArticles = [];
            const seen = new Set();

            articles.forEach(article => {
                const key = (article.title || '').trim().toLowerCase();
                if (key && !seen.has(key)) {
                    seen.add(key);
                    uniqueArticles.push(article);
                }
            });

            if (!uniqueArticles.length) {
                showFallback('Aucun article filtré n’a pu être chargé. Affichage des liens de secours :');
                return;
            }

            rssStatus.textContent = '';
            uniqueArticles.slice(0, 6).forEach(addItem);
        })
        .catch(() => {
            showFallback(
                'Le flux RSS est bloqué par le navigateur ou le service proxy. Affichage des liens de secours :'
            );
        });

    const memoModal = document.getElementById('veilleMemoModal');
    const openMemo = document.getElementById('openVeilleMemo');
    const closeMemo = document.getElementById('closeVeilleMemo');

    function openMemoModal() {
        memoModal.classList.add('open');
        memoModal.setAttribute('aria-hidden', 'false');
    }

    function closeMemoModal() {
        memoModal.classList.remove('open');
        memoModal.setAttribute('aria-hidden', 'true');
    }

    openMemo.addEventListener('click', openMemoModal);
    closeMemo.addEventListener('click', closeMemoModal);

    memoModal.addEventListener('click', function(e) {
        if (e.target.classList.contains('veille-memo-backdrop')) {
            closeMemoModal();
        }
    });
});
</script>