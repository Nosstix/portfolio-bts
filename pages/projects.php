                </a>
                <a id="project-modal-github" class="project-modal-pdf" href="#" target="_blank" rel="noopener" style="display:none;">
                    <i class="fab fa-github"></i> Voir sur GitHub
                </a>
            </div>
        </div>
    `;
    document.body.appendChild(modal);

    const titleEl = document.getElementById('project-modal-title');
    const sourceEl = document.getElementById('project-modal-source');
    const tagsEl = document.getElementById('project-modal-tags');
    const detailsEl = document.getElementById('project-modal-details');
    const pdfEl = document.getElementById('project-modal-pdf');
    const githubEl = document.getElementById('project-modal-github');

    document.querySelectorAll('.project-card, .other-project-mini').forEach(card => {
        card.addEventListener('click', () => {
            titleEl.textContent = card.dataset.name || 'Projet';
            sourceEl.textContent = card.dataset.source || '';
            tagsEl.textContent = card.dataset.tags || '';
            detailsEl.textContent = card.dataset.details || card.dataset.short || '';

            const pdf = card.dataset.pdf || '';
            if (pdf.trim() !== '') {
                pdfEl.href = pdf;
                pdfEl.style.display = 'inline-flex';
            } else {
                pdfEl.removeAttribute('href');
                pdfEl.style.display = 'none';
            }

            const github = card.dataset.github || '';
            if (github.trim() !== '') {
                githubEl.href = github;
                githubEl.style.display = 'inline-flex';
            } else {
                githubEl.style.display = 'none';
            }
            modal.classList.add('open');
        });
    });

    modal.addEventListener('click', e => {
        if (e.target.classList.contains('project-modal-close') || e.target.classList.contains('project-modal-backdrop')) {
            modal.classList.remove('open');
        }
    });
});
</script>
